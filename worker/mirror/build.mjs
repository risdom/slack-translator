// Bundles the two HTML pages into mirror_page.js (run before deploy: node mirror/build.mjs).
import { readFileSync, writeFileSync } from "fs";
const page = readFileSync(new URL("./page.html", import.meta.url), "utf8"), admin = readFileSync(new URL("./admin.html", import.meta.url), "utf8");
writeFileSync(new URL("../mirror_page.js", import.meta.url),
  `// Generated by mirror/build.mjs from mirror/page.html and mirror/admin.html - edit those, then rebuild.\nexport const PAGE = ${JSON.stringify(page)};\nexport const ADMIN_PAGE = ${JSON.stringify(admin)};\n`);
console.log("mirror_page.js written");
